def check(program, observation, expected, phase="postcondition", comparator="equals", note=""):
    return {
        "phase": phase,
        "program": program,
        "observation": observation,
        "comparator": comparator,
        "expected": expected,
        "tolerance": 0.0,
        "note": note,
    }


def unit(uid, category, kind, description, inputs, outputs, implementation,
         observations, dependencies=None, examples=None, checks=None,
         preconditions=None, postconditions=None, invariants=None,
         effects=None, context=None, tags=None, status="verified",
         unsupported=""):
    return {
        "knowledgeId": uid,
        "version": "1",
        "category": category,
        "kind": kind,
        "referenceKind": ("callable" if implementation.startswith("core:") else implementation.split(":", 1)[0]),
        "description": description,
        "inputTypes": inputs,
        "outputTypes": outputs,
        "parameters": [],
        "preconditions": preconditions or [],
        "postconditions": postconditions or [],
        "invariants": invariants or [],
        "allowedEffects": effects or [],
        "requiredContext": context or [],
        "dependencies": dependencies or [],
        "implementationRef": implementation,
        "observationRefs": observations,
        "examples": examples or [],
        "checks": checks or [],
        "source": "MPL V0.4.0 Final frozen semantics / Stdlib / benchmark",
        "license": "MPL project",
        "verificationStatus": status,
        "unsupportedReason": unsupported,
        "tags": tags or [],
    }


